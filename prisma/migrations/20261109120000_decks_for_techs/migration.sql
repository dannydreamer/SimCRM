-- Facilitator decks widened to the Techs — spec §14 F-06, "Widening to the Techs"
--
-- DeckFile: a file now belongs to a facilitator (ownerId → facilitatorId, renamed
-- so the pilot's template and decks stay Daniel's) and a deck records who
-- generated it and from which template. Sharing goes: every Tech sees every deck.
-- WorkshopDeckContent: the text approved for a workshop, reused by every deck.
--
-- Apply by hand through the session pooler, then record the migration row in
-- _prisma_migrations (spec §2.2).

-- DeckFile: owner → facilitator, keeping the rows
ALTER TABLE "DeckFile" RENAME COLUMN "ownerId" TO "facilitatorId";
ALTER TABLE "DeckFile" RENAME CONSTRAINT "DeckFile_ownerId_fkey" TO "DeckFile_facilitatorId_fkey";
ALTER INDEX "DeckFile_ownerId_kind_idx" RENAME TO "DeckFile_facilitatorId_kind_idx";

ALTER TABLE "DeckFile" DROP COLUMN "sharedAt",
ADD COLUMN     "generatedById" TEXT,
ADD COLUMN     "templateId" TEXT,
ADD COLUMN     "label" TEXT,
ADD COLUMN     "tokens" TEXT;

-- The pilot's decks were generated by their facilitator
UPDATE "DeckFile" SET "generatedById" = "facilitatorId" WHERE "kind" = 'DECK';

ALTER TABLE "DeckFile" ADD CONSTRAINT "DeckFile_generatedById_fkey" FOREIGN KEY ("generatedById") REFERENCES "Person"("id") ON DELETE SET NULL ON UPDATE CASCADE;
ALTER TABLE "DeckFile" ADD CONSTRAINT "DeckFile_templateId_fkey" FOREIGN KEY ("templateId") REFERENCES "DeckFile"("id") ON DELETE SET NULL ON UPDATE CASCADE;

-- CreateTable
CREATE TABLE "WorkshopDeckContent" (
    "workshopId" TEXT NOT NULL,
    "organization" TEXT NOT NULL DEFAULT '',
    "groupName" TEXT NOT NULL DEFAULT '',
    "schedule" TEXT NOT NULL DEFAULT '[]',
    "scheduleFileName" TEXT,
    "scenarios" TEXT NOT NULL DEFAULT '[]',
    "updatedAt" TIMESTAMP(3) NOT NULL,
    "updatedById" TEXT,

    CONSTRAINT "WorkshopDeckContent_pkey" PRIMARY KEY ("workshopId")
);

ALTER TABLE "WorkshopDeckContent" ADD CONSTRAINT "WorkshopDeckContent_workshopId_fkey" FOREIGN KEY ("workshopId") REFERENCES "Workshop"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "WorkshopDeckContent" ADD CONSTRAINT "WorkshopDeckContent_updatedById_fkey" FOREIGN KEY ("updatedById") REFERENCES "Person"("id") ON DELETE SET NULL ON UPDATE CASCADE;

-- Every table Prisma creates inherits full anon/authenticated privileges from
-- Supabase's default privileges (spec §2.3.1). The disabled Data API keeps
-- them unreachable; revoke them here as well.
REVOKE ALL ON TABLE "WorkshopDeckContent" FROM anon, authenticated;
